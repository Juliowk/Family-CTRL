-- Categoria e medida sugeridas pela IA (Gemini) para um produto, por família. Guardar a resposta
-- evita perguntar de novo pelo mesmo produto: o plano gratuito da API tem limite de chamadas.
-- Só entram aqui as respostas da IA; o histórico da família e o dicionário embutido não precisam.
create table sugestoes_item (
    id               bigint generated by default as identity primary key,
    familia_id       bigint       not null references familias (id) on delete cascade,
    -- Nome comparável: minúsculo, sem acento, no singular ("Mussarelas" → "mussarela")
    nome_normalizado varchar(120) not null,
    -- Categoria excluída: a sugestão some junto e a IA é consultada de novo se preciso
    categoria_id     bigint       not null references categorias (id) on delete cascade,
    medida           varchar(10)  not null,
    criado_em        timestamp with time zone not null default now(),
    constraint ck_sugestoes_item_medida check (medida in ('UNIDADE', 'KG'))
);

create unique index ux_sugestoes_item_familia_nome on sugestoes_item (familia_id, nome_normalizado);
create index ix_sugestoes_item_categoria on sugestoes_item (categoria_id);
