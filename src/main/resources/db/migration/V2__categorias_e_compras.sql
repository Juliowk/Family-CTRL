-- Planejamento por categoria e registro de compras.
-- A lista vira o "plano" reutilizável; cada ida ao mercado finalizada vira uma compra
-- (cópia imutável dos itens, preços, mercado e valor).

-- ---------------------------------------------------------------- categorias
create table categorias (
    id          bigint generated by default as identity primary key,
    familia_id  bigint      not null references familias (id) on delete cascade,
    nome        varchar(50) not null,
    ordem       integer     not null,
    -- "Outros": não pode ser excluída, recebe os itens de categorias excluídas
    fixa        boolean     not null default false
);

create unique index ux_categorias_familia_nome on categorias (familia_id, lower(nome));
create index ix_categorias_familia on categorias (familia_id, ordem);

-- Famílias que já existem ganham as categorias padrão (as novas ganham no primeiro acesso)
insert into categorias (familia_id, nome, ordem, fixa)
select f.id, c.nome, c.ordem, c.fixa
from familias f
cross join (values
    ('Açougue, Embutidos e Peixaria', 1, false),
    ('Mercearia e Alimentos Básicos', 2, false),
    ('Laticínios, Frios e Ovos',      3, false),
    ('Padaria',                       4, false),
    ('Hortifrúti e Congelados',       5, false),
    ('Limpeza',                       6, false),
    ('Higiene Pessoal',               7, false),
    ('Outros',                        8, true)
) as c (nome, ordem, fixa);

-- ---------------------------------------------------------------- itens
alter table itens add column categoria_id bigint references categorias (id);

-- Itens existentes vão para "Outros" da família dona da lista
update itens i
set categoria_id = c.id
from listas l, categorias c
where l.id = i.lista_id and c.familia_id = l.familia_id and c.fixa;

alter table itens alter column categoria_id set not null;
create index ix_itens_categoria on itens (categoria_id);

alter table itens rename column quantidade to quantidade_planejada;
alter table itens rename column comprado to pego;
alter table itens rename column comprado_por to pego_por;
alter table itens drop column observacao;

-- Estado da compra em andamento (zerado ao finalizar ou ao "desmarcar todos")
alter table itens add column pego_em          timestamp with time zone;
alter table itens add column quantidade_pega  numeric(10, 3);
alter table itens add column tipo_preco       varchar(10) not null default 'UNIDADE';
alter table itens add column preco            numeric(10, 2);
alter table itens add column marca            varchar(60);
-- Item não planejado, adicionado durante a compra
alter table itens add column extra            boolean not null default false;

update itens set pego_em = atualizado_em where pego;

alter table itens add constraint ck_itens_tipo_preco check (tipo_preco in ('UNIDADE', 'KG'));

-- ---------------------------------------------------------------- listas
-- "Arquivada" deixa de existir: o histórico agora são as compras concluídas
alter table listas drop column arquivada;

-- ---------------------------------------------------------------- compras
create table compras (
    id              bigint generated by default as identity primary key,
    familia_id      bigint        not null references familias (id) on delete cascade,
    -- A compra sobrevive à exclusão da lista: guarda o nome dela
    lista_id        bigint        references listas (id) on delete set null,
    lista_nome      varchar(100)  not null,
    mercado         varchar(100)  not null,
    data_compra     date          not null,
    valor_itens     numeric(10, 2) not null,
    valor_variavel  numeric(10, 2) not null,
    valor_total     numeric(10, 2) not null,
    finalizada_por  bigint        not null references usuarios (id),
    finalizada_em   timestamp with time zone not null default now()
);

create index ix_compras_familia_data on compras (familia_id, data_compra desc);

create table compra_itens (
    id                    bigint generated by default as identity primary key,
    compra_id             bigint        not null references compras (id) on delete cascade,
    nome                  varchar(120)  not null,
    categoria             varchar(50)   not null,
    categoria_ordem       integer       not null,
    quantidade_planejada  varchar(30),
    pego                  boolean       not null,
    quantidade_pega       numeric(10, 3),
    tipo_preco            varchar(10)   not null,
    preco                 numeric(10, 2),
    subtotal              numeric(10, 2),
    marca                 varchar(60),
    extra                 boolean       not null
);

create index ix_compra_itens_compra on compra_itens (compra_id);
