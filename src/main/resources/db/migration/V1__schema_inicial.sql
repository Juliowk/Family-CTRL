-- Schema inicial do Family Ctrl

create table usuarios (
    id          bigint generated by default as identity primary key,
    nome        varchar(100) not null,
    email       varchar(255) not null,
    senha_hash  varchar(100) not null,
    criado_em   timestamp with time zone not null default now(),
    constraint uk_usuarios_email unique (email)
);

create table familias (
    id              bigint generated by default as identity primary key,
    nome            varchar(100) not null,
    codigo_convite  varchar(12)  not null,
    criado_em       timestamp with time zone not null default now(),
    constraint uk_familias_codigo_convite unique (codigo_convite)
);

create table membros_familia (
    familia_id  bigint      not null references familias (id) on delete cascade,
    usuario_id  bigint      not null references usuarios (id),
    papel       varchar(10) not null,
    entrou_em   timestamp with time zone not null default now(),
    primary key (familia_id, usuario_id),
    constraint ck_membros_familia_papel check (papel in ('ADMIN', 'MEMBRO'))
);

create index ix_membros_familia_usuario on membros_familia (usuario_id);

create table listas (
    id          bigint generated by default as identity primary key,
    familia_id  bigint       not null references familias (id) on delete cascade,
    nome        varchar(100) not null,
    arquivada   boolean      not null default false,
    criada_por  bigint       not null references usuarios (id),
    criada_em   timestamp with time zone not null default now()
);

create index ix_listas_familia on listas (familia_id);

create table itens (
    id              bigint generated by default as identity primary key,
    lista_id        bigint       not null references listas (id) on delete cascade,
    nome            varchar(120) not null,
    quantidade      varchar(30),
    observacao      varchar(255),
    comprado        boolean      not null default false,
    comprado_por    bigint       references usuarios (id),
    adicionado_por  bigint       not null references usuarios (id),
    criado_em       timestamp with time zone not null default now(),
    atualizado_em   timestamp with time zone not null default now()
);

create index ix_itens_lista on itens (lista_id);
